/** 고른 성향 순서대로 받아 결과 키를 돌려준다. 점수가 같으면 더 나중에 고른 성향이 앞선다. */
export function resultKey(picks: Trait[]): string {
  const rank = [...TRAITS].sort((a, b) => {
    const n = (t: Trait) => picks.filter(p => p === t).length
    return n(b) - n(a) || picks.lastIndexOf(b) - picks.lastIndexOf(a)
  })
  return rank[0]! + rank[1]!
}
