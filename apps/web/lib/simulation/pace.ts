/**
 * 11/24 사용자: 이어서 받기 + 전개 설정. 화면과 서버가 같이 쓰는 값이라 DB·서버 전용 코드를 불러오지 않는다.
 *
 * 이어서 받기 — 할 말이 없을 때 입력 없이 다음 장면을 받는다. 턴의 모양(보낸 말 + 답)은 그대로 두려고 보낸 말 자리에 이 표식을 넣고,
 * 화면은 그 말풍선을 그리지 않는다. 되돌리기·다시 받기도 이 표식으로 같은 턴임을 안다.
 */
export const CONTINUE_INPUT = '(이어서)'

export const CONTINUE_DIRECTIVE = `사용자가 '이어서 받기'를 눌렀습니다. 사용자의 입력 '${CONTINUE_INPUT}'는 대사나 행동이 아니라 다음 장면을 이어 달라는 선택입니다 — 사용자는 이번에 아무 말도 행동도 하지 않았습니다. 직전 답이 끝난 자리에서 바로 이어서, 캐릭터가 스스로 말하고 움직이며 상황을 한 걸음 진전시킵니다. 직전 답의 내용을 되풀이하거나 요약하지 않고, 사용자의 대사·행동·생각을 대신 쓰지 않으며, '${CONTINUE_INPUT}'라는 글을 언급하지 않습니다.`

/** 전개 속도 — follow: 내가 이끌기, balanced: 보통(지시 없음), lead: 캐릭터가 이끌기. */
export type Pace = 'follow' | 'balanced' | 'lead'
export const PACES: readonly Pace[] = ['follow', 'balanced', 'lead']

/** 이번 대사에만 붙는 전개 지시. 보통 + 건너뛰기 꺼짐이면 빈 글(지시문이 그대로다). */
export function paceDirective(pace: Pace | undefined, timeSkip: boolean): string {
  const lines = [
    pace === 'follow' ? '전개 속도(사용자 설정: 내가 이끌기): 이번 응답은 사용자가 방금 한 말·행동에 반응하는 데 머뭅니다. 새 사건·새 인물·장소 이동을 먼저 만들지 말고, 다음에 무엇을 할지는 사용자가 정하게 둡니다.'
      : pace === 'lead' ? '전개 속도(사용자 설정: 캐릭터가 이끌기): 캐릭터가 이야기를 끌고 갑니다. 이번 응답에서 상황을 눈에 띄게 한 걸음 진전시킵니다 — 새 사건, 갈등, 제안, 장소 이동, 주변 인물의 개입 가운데 지금 장면에 맞는 것을 캐릭터가 스스로 일으킵니다. 같은 자리에서 맴돌거나 사용자에게 다음을 묻기만 하고 끝내지 않습니다. 사용자의 대사·행동·결정은 대신 쓰지 않습니다.'
      : '',
    timeSkip ? '시간 건너뛰기(사용자 설정: 허용): 아무 일 없이 늘어지는 시간(이동·기다림·잠·반복되는 일과)은 한두 문장으로 넘기고, 다음 의미 있는 순간에서 장면을 이어 갑니다. 얼마나 지났는지는 서술로 분명히 알립니다. 지금 벌어지고 있는 중요한 장면은 건너뛰지 않습니다.' : '',
  ].filter(Boolean)
  return lines.join('\n')
}
